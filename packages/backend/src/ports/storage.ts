import type { Readable } from 'node:stream';

export interface StoredContent {
  bytes: number;
  sha256: string;
}
export interface StorageCommit {
  /**
   * Persist the immutable final key while the caller holds its database fence.
   * The callback must invoke persist exactly once before returning successfully.
   */
  (content: StoredContent, persist: () => Promise<void>): Promise<void>;
}
export interface TemporaryFileSweepResult {
  deleted: number;
  failed: number;
}
export interface ContentRange {
  start: number;
  end: number;
}
export interface StoragePort {
  readonly backendKey: string;
  readonly namespace: string;
  /** Exclusive immutable write. Keys are generated by the server, never supplied by users. */
  put(
    key: string,
    source: AsyncIterable<Uint8Array>,
    limits: { maxBytes: number; expectedBytes?: number; commit?: StorageCommit },
  ): Promise<StoredContent>;
  inspect(key: string): Promise<StoredContent>;
  open(key: string, range?: ContentRange): Promise<{ stream: Readable; bytes: number }>;
  withLocalFile<T>(key: string, use: (path: string) => Promise<T>): Promise<T>;
  /** Only the reference-aware cleanup service may call this. */
  remove(key: string): Promise<void>;
  /** Remove only adapter-owned, expired staging files and locks. */
  sweepTemporaryFiles?(options: {
    olderThan: Date;
    limit: number;
  }): Promise<TemporaryFileSweepResult>;
}
